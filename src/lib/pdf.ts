import { jsPDF } from 'jspdf'
import type { Lens, Project, Projector, Solution } from '../types'
import { feetInches, int, megapixels, pct, ppi } from './units'

/**
 * PDF system report.
 *
 * A4 portrait, millimetres. Everything is drawn as vectors (no rasterised
 * canvas) so the diagrams stay crisp when the report is printed or zoomed.
 */

const PAGE_W = 210
const PAGE_H = 297
const M = 16 // page margin
const CONTENT_W = PAGE_W - M * 2

const INK = { r: 26, g: 32, b: 44 }
const MUTED = { r: 110, g: 120, b: 135 }
const RULE = { r: 205, g: 212, b: 222 }
const ACCENT = { r: 22, g: 122, b: 185 }
const BLEND = { r: 240, g: 160, b: 40 }
const DANGER = { r: 190, g: 45, b: 45 }

type Ctx = {
  doc: jsPDF
  y: number
  page: number
}

function setFill(doc: jsPDF, c: { r: number; g: number; b: number }) {
  doc.setFillColor(c.r, c.g, c.b)
}
function setDraw(doc: jsPDF, c: { r: number; g: number; b: number }) {
  doc.setDrawColor(c.r, c.g, c.b)
}
function setText(doc: jsPDF, c: { r: number; g: number; b: number }) {
  doc.setTextColor(c.r, c.g, c.b)
}

function ensure(ctx: Ctx, needed: number) {
  if (ctx.y + needed > PAGE_H - 22) newPage(ctx)
}

function newPage(ctx: Ctx) {
  footer(ctx)
  ctx.doc.addPage()
  ctx.page += 1
  ctx.y = M
}

function footer(ctx: Ctx) {
  const { doc } = ctx
  doc.setFontSize(7)
  setText(doc, MUTED)
  setDraw(doc, RULE)
  doc.setLineWidth(0.2)
  doc.line(M, PAGE_H - 16, PAGE_W - M, PAGE_H - 16)
  doc.text(
    'Generated by Blend Calc. Figures are geometric estimates for planning only — ' +
      'verify against manufacturer datasheets and a site survey before committing.',
    M,
    PAGE_H - 12,
    { maxWidth: CONTENT_W - 20 },
  )
  doc.text(`Page ${ctx.page}`, PAGE_W - M, PAGE_H - 12, { align: 'right' })
}

/**
 * `keepWith` is the space the first chunk of the section needs. Without it a
 * heading lands at the foot of a page and its table starts on the next one,
 * which reads as a missing section.
 */
function heading(ctx: Ctx, text: string, keepWith = 22) {
  ensure(ctx, 16 + keepWith)
  const { doc } = ctx
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  setText(doc, INK)
  doc.text(text, M, ctx.y)
  ctx.y += 2
  setDraw(doc, ACCENT)
  doc.setLineWidth(0.5)
  doc.line(M, ctx.y, M + 22, ctx.y)
  ctx.y += 5
  doc.setFont('helvetica', 'normal')
}

/** A two-column label/value block. */
function kvGrid(ctx: Ctx, rows: [string, string][], cols = 2) {
  const { doc } = ctx
  const colW = CONTENT_W / cols
  const rowH = 5.6
  const perCol = Math.ceil(rows.length / cols)
  ensure(ctx, perCol * rowH + 4)
  doc.setFontSize(8.5)

  rows.forEach((row, i) => {
    const col = Math.floor(i / perCol)
    const line = i % perCol
    const x = M + col * colW
    const y = ctx.y + line * rowH
    setText(doc, MUTED)
    doc.setFont('helvetica', 'normal')
    doc.text(row[0], x, y)
    setText(doc, INK)
    doc.setFont('helvetica', 'bold')
    doc.text(row[1], x + colW - 4, y, { align: 'right' })
  })
  doc.setFont('helvetica', 'normal')
  ctx.y += perCol * rowH + 4
}

function table(ctx: Ctx, headers: string[], rows: string[][], widths: number[]) {
  const { doc } = ctx
  const rowH = 5.4
  ensure(ctx, rowH * (rows.length + 1) + 4)
  const total = widths.reduce((a, b) => a + b, 0)
  const scale = CONTENT_W / total
  const w = widths.map((x) => x * scale)

  setFill(doc, { r: 238, g: 242, b: 247 })
  doc.rect(M, ctx.y - 3.8, CONTENT_W, rowH, 'F')
  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  setText(doc, INK)
  let x = M + 1.5
  headers.forEach((h, i) => {
    const right = i > 0
    doc.text(h, right ? x + w[i] - 3 : x, ctx.y, { align: right ? 'right' : 'left' })
    x += w[i]
  })
  ctx.y += rowH

  doc.setFont('helvetica', 'normal')
  rows.forEach((r, ri) => {
    if (ctx.y + rowH > PAGE_H - 22) {
      newPage(ctx)
      ctx.y += 2
    }
    if (ri % 2 === 1) {
      setFill(doc, { r: 248, g: 250, b: 252 })
      doc.rect(M, ctx.y - 3.8, CONTENT_W, rowH, 'F')
    }
    setText(doc, INK)
    let cx = M + 1.5
    r.forEach((cell, i) => {
      const right = i > 0
      doc.text(cell, right ? cx + w[i] - 3 : cx, ctx.y, { align: right ? 'right' : 'left' })
      cx += w[i]
    })
    ctx.y += rowH
  })
  ctx.y += 3
}

function paragraph(ctx: Ctx, text: string, color = MUTED, size = 8) {
  const { doc } = ctx
  doc.setFontSize(size)
  setText(doc, color)
  const lines = doc.splitTextToSize(text, CONTENT_W) as string[]
  ensure(ctx, lines.length * 4 + 2)
  doc.text(lines, M, ctx.y)
  ctx.y += lines.length * 4 + 2
}

