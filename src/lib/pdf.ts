export function buildReport(
  project: Project,
  sol: Solution,
  projector: Projector,
  lens: Lens | null,
): jsPDF {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' })
  const ctx: Ctx = { doc, y: M, page: 1 }
  const geo = project.screen.geometry
  const { columns, rows } = project.array
  const count = columns * rows

  // -- Title block ----------------------------------------------------------
  setFill(doc, { r: 13, g: 27, b: 42 })
  doc.rect(0, 0, PAGE_W, 26, 'F')
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  setText(doc, { r: 255, g: 255, b: 255 })
  doc.text(project.name || 'Untitled blend', M, 13)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  setText(doc, { r: 170, g: 190, b: 210 })
  const sub = [
    project.client ? `Client: ${project.client}` : null,
    `${count} × ${projector.brand} ${projector.model}`,
    new Date().toISOString().slice(0, 10),
  ]
    .filter(Boolean)
    .join('   ·   ')
  doc.text(sub, M, 20)
  ctx.y = 34

  // -- Headline figures -----------------------------------------------------
  heading(ctx, 'System summary')
  kvGrid(ctx, [
    ['Screen', geo.kind === 'flat' ? 'Flat' : `Cylindrical, r = ${geo.radius.toFixed(2)} m`],
    ['Screen size', `${geo.width.toFixed(3)} × ${geo.height.toFixed(3)} m`],
    ['Screen size (imperial)', `${feetInches(geo.width)} × ${feetInches(geo.height)}`],
    ['Screen area', `${(geo.width * geo.height).toFixed(2)} m²`],
    ['Array', `${columns} across × ${rows} high (${count} projectors)`],
    ['Placement', project.array.placement === 'per-tile' ? 'One projector per tile' : 'Common rig position'],
    ['Throw distance', `${project.array.throwDistance.toFixed(3)} m (${feetInches(project.array.throwDistance)})`],
    ['Screen gain', project.screen.gain.toFixed(2)],
  ])

  heading(ctx, 'System resolution')
  kvGrid(ctx, [
    [
      'Canvas resolution',
      `${int(sol.pixels.canvasPixelWidth)} × ${int(sol.pixels.canvasPixelHeight)} px`,
    ],
    ['Canvas pixels (unique)', megapixels(sol.pixels.uniquePixels)],
    ['Canvas aspect', `${(sol.pixels.canvasPixelWidth / sol.pixels.canvasPixelHeight).toFixed(3)}:1`],
    ['Projector native', `${int(projector.nativeWidth)} × ${int(projector.nativeHeight)} px`],
    ['Total projector pixels', megapixels(sol.pixels.totalProjectorPixels)],
    ['Pixel density', `${sol.pixelDensity.toFixed(1)} px/m  ·  ${ppi(sol.pixelDensity).toFixed(1)} PPI`],
    ['Est. screen luminance', `${sol.luminanceFootLamberts.toFixed(1)} fL  ·  ${sol.luminanceNits.toFixed(0)} nits`],
    ['Total light output', `${int(projector.lumens * count)} lm`],
  ])

  // -- The data double ------------------------------------------------------
  heading(ctx, 'Overlap — the doubled region', 46)
  paragraph(
    ctx,
    'Every pixel in a blend band is produced by two projectors (four where a ' +
      'horizontal and a vertical blend cross). Those pixels are paid for twice in ' +
      'projector count, rigging and data, but appear once on screen.',
  )
  table(
    ctx,
    ['Coverage', 'Area (canvas px)', 'Share of canvas', 'On screen'],
    [
      [
        'Single projector',
        int(sol.pixels.singleCoveredPixels),
        pct(sol.pixels.singleCoveredPixels / sol.pixels.uniquePixels),
        '—',
      ],
      [
        'Two projectors (doubled)',
        int(sol.pixels.doubleCoveredPixels),
        pct(sol.pixels.doubleCoveredPixels / sol.pixels.uniquePixels),
        `${sol.hOverlapMetres.toFixed(3)} m bands`,
      ],
      [
        'Four projectors (corners)',
        int(sol.pixels.quadCoveredPixels),
        pct(sol.pixels.quadCoveredPixels / sol.pixels.uniquePixels),
        rows > 1 ? `${sol.vOverlapMetres.toFixed(3)} m tall` : '—',
      ],
    ],
    [34, 22, 20, 24],
  )
  kvGrid(
    ctx,
    [
      ['Horizontal blend', `${pct(sol.hOverlap)} of image  ·  ${int(sol.pixels.hBlendPixels)} px  ·  ${sol.hOverlapMetres.toFixed(3)} m`],
      ['Vertical blend', rows > 1 ? `${pct(sol.vOverlap)} of image  ·  ${int(sol.pixels.vBlendPixels)} px  ·  ${sol.vOverlapMetres.toFixed(3)} m` : 'n/a (single row)'],
      ['Redundant pixels', `${megapixels(sol.pixels.redundantPixels)} (${int(sol.pixels.redundantPixels)})`],
      ['Pixel efficiency loss', pct(sol.pixels.overlapEfficiencyLoss)],
    ],
    1,
  )

  // -- Diagram --------------------------------------------------------------
  heading(ctx, 'Layout', 60)
  frontElevation(ctx, sol, columns, rows, geo.width, geo.height)
  if (geo.kind === 'cylindrical') {
    planView(ctx, sol, geo.radius, geo.width, project.array.throwDistance)
  }

  // -- Optics ---------------------------------------------------------------
  heading(ctx, 'Optics and lens', 34)
  kvGrid(ctx, [
    ['Image per projector', `${sol.tileWidth.toFixed(3)} × ${sol.tileHeight.toFixed(3)} m`],
    ['Image (imperial)', `${feetInches(sol.tileWidth)} × ${feetInches(sol.tileHeight)}`],
    ['Lens', lens ? lens.name : 'Not selected'],
    ['Lens range', lens ? `${lens.throwRatioMin.toFixed(2)}–${lens.throwRatioMax.toFixed(2)}:1` : '—'],
    [
      'Required throw ratio',
      `${Math.min(...sol.columns.map((c) => c.requiredThrowRatio)).toFixed(3)}–${Math.max(
        ...sol.columns.map((c) => c.requiredThrowRatio),
      ).toFixed(3)}:1`,
    ],
    [
      'Zoom position',
      lens && lens.throwRatioMax > lens.throwRatioMin
        ? `${pct(sol.lensZoomPosition, 0)} from wide`
        : 'Fixed lens',
    ],
  ])

  if (geo.kind === 'cylindrical' || project.array.placement === 'common-point') {
    table(
      ctx,
      ['Column', 'Throw', 'Slant', 'Image width', 'Throw ratio', 'H shift', 'Off-axis'],
      sol.columns.map((c) => [
        `${c.column + 1}`,
        `${c.throwDistance.toFixed(3)} m`,
        `${c.slantDistance.toFixed(3)} m`,
        `${c.flatImageWidth.toFixed(3)} m`,
        `${c.requiredThrowRatio.toFixed(3)}:1`,
        `${c.hShiftPct.toFixed(1)}%`,
        `${c.offAxisDeg.toFixed(1)}°`,
      ]),
      [14, 18, 18, 20, 18, 14, 14],
    )
    paragraph(
      ctx,
      'Throw is the perpendicular distance the throw ratio is defined against. Slant is the ' +
        'straight-line distance to the tile centre — the one you measure on site.',
    )
    if (geo.kind === 'cylindrical') {
      kvGrid(
        ctx,
        [
          ['Wrap angle', `${sol.wrapAngleDeg.toFixed(1)}°`],
          ['Chord width', `${(2 * geo.radius * Math.sin(geo.width / geo.radius / 2)).toFixed(3)} m`],
          ['Height at tile edge', `${pct(sol.curveHeightRatio)} of centre — oversize and mask the difference`],
        ],
        1,
      )
    }
  }

  // -- Per-projector schedule ----------------------------------------------
  heading(ctx, 'Projector schedule', 34)
  const schedule: string[][] = []
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < columns; c++) {
      const optics = sol.columns[c]
      schedule.push([
        rows > 1 ? `R${r + 1}C${c + 1}` : `P${c + 1}`,
        `${projector.brand} ${projector.model}`,
        lens ? lens.name : '—',
        `${optics.requiredThrowRatio.toFixed(3)}:1`,
        `${optics.slantDistance.toFixed(2)} m`,
        `${c > 0 ? 'L' : '·'}${c < columns - 1 ? 'R' : '·'}${r > 0 ? 'T' : '·'}${r < rows - 1 ? 'B' : '·'}`,
      ])
    }
  }
  table(
    ctx,
    ['Position', 'Body', 'Lens', 'Throw ratio', 'Throw', 'Blend edges'],
    schedule,
    [16, 34, 30, 18, 16, 18],
  )
  paragraph(
    ctx,
    'Blend edges: L/R/T/B marks which edges of that projector carry a soft edge. ' +
      'A dot means that edge is a hard edge of the canvas.',
  )

  // -- Diagnostics ----------------------------------------------------------
  if (sol.diagnostics.length) {
    heading(ctx, 'Notes and warnings', 14)
    doc.setFontSize(8)
    for (const d of sol.diagnostics) {
      const color = d.severity === 'error' ? DANGER : d.severity === 'warning' ? { r: 170, g: 110, b: 20 } : MUTED
      const label = d.severity === 'error' ? 'ERROR' : d.severity === 'warning' ? 'WARNING' : 'NOTE'
      const lines = doc.splitTextToSize(`${label}: ${d.message}`, CONTENT_W - 4) as string[]
      ensure(ctx, lines.length * 3.8 + 3)
      setDraw(doc, color)
      doc.setLineWidth(0.9)
      doc.line(M, ctx.y - 3, M, ctx.y + lines.length * 3.8 - 4)
      setText(doc, color)
      doc.text(lines, M + 3, ctx.y)
      ctx.y += lines.length * 3.8 + 2.5
    }
  }

  if (projector.unverified) {
    ensure(ctx, 16)
    setFill(doc, { r: 253, g: 240, b: 235 })
    setDraw(doc, DANGER)
    doc.setLineWidth(0.4)
    doc.rect(M, ctx.y - 4, CONTENT_W, 13, 'FD')
    setText(doc, DANGER)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(8)
    doc.text('Unverified projector data', M + 3, ctx.y + 0.5)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7.5)
    doc.text(
      `The specifications for ${projector.brand} ${projector.model} are seed data shipped with ` +
        `the app and have not been checked against a datasheet. Confirm before ordering.`,
      M + 3,
      ctx.y + 5,
      { maxWidth: CONTENT_W - 6 },
    )
    ctx.y += 16
  }

  if (project.notes?.trim()) {
    heading(ctx, 'Project notes', 14)
    paragraph(ctx, project.notes.trim(), INK, 8.5)
  }

  footer(ctx)
  return doc
}

export function reportFilename(project: Project): string {
  const safe = (project.name || 'blend').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '')
  return `${safe.toLowerCase() || 'blend'}-report.pdf`
}
