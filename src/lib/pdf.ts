/**
 * Front elevation: the screen rectangle with every projector tile drawn over
 * it and the overlap bands shaded. This is the drawing people actually look at.
 */
function frontElevation(
  ctx: Ctx,
  sol: Solution,
  columns: number,
  rows: number,
  screenW: number,
  screenH: number,
) {
  const { doc } = ctx
  const maxW = CONTENT_W
  const maxH = 74
  const aspect = sol.coveredWidth / sol.coveredHeight
  let w = maxW
  let h = w / aspect
  if (h > maxH) {
    h = maxH
    w = h * aspect
  }
  ensure(ctx, h + 16)
  const x0 = M + (CONTENT_W - w) / 2
  const y0 = ctx.y
  const sx = w / sol.coveredWidth
  const sy = h / sol.coveredHeight

  // The screen itself.
  setFill(doc, { r: 250, g: 251, b: 253 })
  setDraw(doc, INK)
  doc.setLineWidth(0.5)
  const scrW = screenW * sx
  const scrH = screenH * sy
  const scrX = x0 + (sol.coveredWidth - screenW) / 2 * sx
  const scrY = y0 + (sol.coveredHeight - screenH) / 2 * sy
  doc.rect(scrX, scrY, scrW, scrH, 'FD')

  const pitchX = sol.tileWidth * (1 - sol.hOverlap)
  const pitchY = sol.tileHeight * (1 - sol.vOverlap)

  // Shade the overlap bands first so tile outlines sit on top.
  setFill(doc, BLEND)
  for (let c = 0; c < columns - 1; c++) {
    const bx = x0 + (c * pitchX + sol.tileWidth - sol.hOverlapMetres) * sx
    doc.rect(bx, y0, sol.hOverlapMetres * sx, h, 'F')
  }
  for (let r = 0; r < rows - 1; r++) {
    const by = y0 + (r * pitchY + sol.tileHeight - sol.vOverlapMetres) * sy
    doc.rect(x0, by, w, sol.vOverlapMetres * sy, 'F')
  }

  // Tile outlines.
  setDraw(doc, ACCENT)
  doc.setLineWidth(0.35)
  doc.setFontSize(6.5)
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < columns; c++) {
      const tx = x0 + c * pitchX * sx
      const ty = y0 + r * pitchY * sy
      doc.rect(tx, ty, sol.tileWidth * sx, sol.tileHeight * sy, 'S')
      setText(doc, ACCENT)
      const label = rows > 1 ? `R${r + 1}C${c + 1}` : `P${c + 1}`
      doc.text(label, tx + 1.5, ty + 4)
    }
  }

  ctx.y = y0 + h + 5
  doc.setFontSize(7)
  setText(doc, MUTED)
  doc.text(
    `Front elevation, to scale. Blue outlines are individual projector images; ` +
      `orange is the overlap ("data double") region.`,
    M,
    ctx.y,
    { maxWidth: CONTENT_W },
  )
  ctx.y += 7
}

/** Plan view for a cylindrical screen: the arc, the tiles, and the rig. */
function planView(ctx: Ctx, sol: Solution, radius: number, arcLen: number, throwD: number) {
  const { doc } = ctx
  const size = 66
  ensure(ctx, size + 14)
  const cx = M + CONTENT_W / 2
  const y0 = ctx.y

  const theta = arcLen / radius
  // Scale so the whole arc plus the rig fits the box.
  const halfSpanX = radius * Math.sin(Math.min(theta, Math.PI) / 2)
  const depth = radius - radius * Math.cos(Math.min(theta, Math.PI) / 2)
  const scale = Math.min((CONTENT_W * 0.42) / Math.max(halfSpanX, 0.001), size / Math.max(depth + throwD * 1.15, 0.001))

  // Screen centre of curvature sits below the arc apex on the page.
  const apexY = y0 + 6
  const centreY = apexY + radius * scale

  const pt = (angle: number, r: number) => ({
    x: cx + r * Math.sin(angle) * scale,
    y: centreY - r * Math.cos(angle) * scale,
  })

  // The arc, drawn as a polyline.
  setDraw(doc, INK)
  doc.setLineWidth(0.7)
  const steps = 120
  let prev = pt(-theta / 2, radius)
  for (let i = 1; i <= steps; i++) {
    const a = -theta / 2 + (theta * i) / steps
    const p = pt(a, radius)
    doc.line(prev.x, prev.y, p.x, p.y)
    prev = p
  }

  // Tile boundaries and their sight lines.
  const thetaTile = sol.tileWidth / radius
  const pitch = (sol.tileWidth * (1 - sol.hOverlap)) / radius
  setDraw(doc, ACCENT)
  doc.setLineWidth(0.3)
  const nCols = sol.columns.length
  for (let c = 0; c < nCols; c++) {
    const phi = (c - (nCols - 1) / 2) * pitch
    const proj = pt(phi, radius - throwD)
    const l = pt(phi - thetaTile / 2, radius)
    const r = pt(phi + thetaTile / 2, radius)
    doc.line(proj.x, proj.y, l.x, l.y)
    doc.line(proj.x, proj.y, r.x, r.y)
    setFill(doc, ACCENT)
    doc.circle(proj.x, proj.y, 0.9, 'F')
  }

  ctx.y = Math.max(centreY - (radius - throwD) * scale, apexY) + 12
  if (ctx.y < y0 + 20) ctx.y = y0 + 20
  doc.setFontSize(7)
  setText(doc, MUTED)
  doc.text(
    `Plan view of the ${((arcLen / radius) * 180 / Math.PI).toFixed(1)}° arc. ` +
      `Dots are projector positions; lines are the edges of each tile.`,
    M,
    ctx.y,
    { maxWidth: CONTENT_W },
  )
  ctx.y += 7
}

